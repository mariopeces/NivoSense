// Generates src/styles/tokens.css from docs/design/tokens.json, the design spec's source of truth.
// Naming follows the spec and its mockups: every token becomes --<group>-<name>; a typography token
// becomes --type-<name>-family / -size / -lh / -weight. Run with `npm run tokens`; a test fails if the
// committed CSS is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = path.resolve(here, "../../docs/design/tokens.json");
export const TOKENS_CSS = path.resolve(here, "../src/styles/tokens.css");

// Groups that describe things rather than values (icon set, basemap URLs) stay out of CSS.
const SKIP = new Set(["icon", "basemap"]);

function fontList(fonts) {
  return fonts.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ");
}

export function flattenTokens(tokens) {
  const vars = [];
  const walk = (node, prefix) => {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("$") || !value || typeof value !== "object") continue;
      if (!("$value" in value)) {
        walk(value, `${prefix}${key}-`);
        continue;
      }
      const name = `${prefix}${key}`;
      const v = value.$value;
      const type = value.$type ?? node.$type;
      if (type === "other" && typeof v === "string" && name.startsWith("motion-")) continue;
      if (Array.isArray(v)) {
        vars.push([name, name.startsWith("motion-easing") ? `cubic-bezier(${v.join(", ")})` : fontList(v)]);
      } else if (typeof v === "object") {
        vars.push([`${name}-family`, `var(--font-family-${v.family})`]);
        vars.push([`${name}-size`, `${v.size}px`]);
        vars.push([`${name}-lh`, `${v.lineHeight}px`]);
        vars.push([`${name}-weight`, String(v.weight)]);
      } else {
        vars.push([name, String(v)]);
      }
    }
  };
  for (const [group, node] of Object.entries(tokens)) {
    if (group.startsWith("$") || SKIP.has(group)) continue;
    walk(node, `${group}-`);
  }
  return vars;
}

export function renderTokensCss(tokens) {
  const vars = flattenTokens(tokens);
  // The play frame is the timeline's step interval, not an animation: under reduced motion play still steps.
  const durations = vars.filter(
    ([name]) => name.startsWith("motion-duration-") && name !== "motion-duration-play-frame",
  );
  return [
    "/* Generated by scripts/build-tokens.mjs from docs/design/tokens.json. Do not edit by hand. */",
    ":root {",
    ...vars.map(([name, value]) => `  --${name}: ${value};`),
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    ...durations.map(([name]) => `    --${name}: 0ms;`),
    "  }",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(TOKENS_JSON, "utf8"));
  writeFileSync(TOKENS_CSS, renderTokensCss(tokens));
  console.log(`wrote ${path.relative(process.cwd(), TOKENS_CSS)}`);
}
